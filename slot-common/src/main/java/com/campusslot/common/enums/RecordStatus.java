package com.campusslot.common.enums;

/**
 * 名额生命周期（需求书 §4.1）。
 *
 * <pre>
 * 可申领 --抢到--> 已锁定(LOCKED) --确认--> 已确认(CONFIRMED)
 *                    |                        |
 *                    +--超时 / 取消--> 已释放(RELEASED) <--取消（验证持有后回补）--+
 * </pre>
 *
 * <p>只有「可申领 → 已锁定」这一步需要严格保护：同一名额绝不能同时给两个人。
 * 「已确认 → 已释放」必须验证持有关系，否则重复取消会让余量虚增。
 *
 * <p>命名用 LOCKED 而不是 PENDING：需求书全文用的是「已锁定」，
 * 代码里叫 PENDING、文档里叫锁定，答辩时每讲一次都要额外解释一遍。
 *
 * <p><b>当前无引用（2026-11-09）</b>：业务代码与 SQL 里用的是状态字符串字面量
 * （`LOCKED` / `CONFIRMED` / `RELEASED`），本枚举没有被任何类引用，**不是状态的唯一来源**。
 * 保留它的理由是上面那张状态机图——把它删了，状态机就只剩散落的字面量。
 */
public enum RecordStatus {

    /** 已锁定，30 分钟确认倒计时中。 */
    LOCKED,

    /** 已确认，名额最终归属。 */
    CONFIRMED,

    /** 已释放（超时未确认或被取消），名额已回补或进入补位队列。 */
    RELEASED
}
